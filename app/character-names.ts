export const allCharacterNames = [...maleNames, ...femaleNames];

export type NamePool = "male" | "female" | "any";

export function randomCharacterName(pool: NamePool = "any", random: () => number = Math.random) {
  const names = pool === "male" ? maleNames : pool === "female" ? femaleNames : allCharacterNames;
  return names[Math.min(names.length - 1, Math.floor(random() * names.length))];
}

export function nameCommand(command: string, random: () => number = Math.random) {
  const normalized = command.trim().toLowerCase();
  if (normalized === "/namem") return { pool: "male" as const, label: "Male name", name: randomCharacterName("male", random) };
  if (normalized === "/namef") return { pool: "female" as const, label: "Female name", name: randomCharacterName("female", random) };
  if (normalized === "/name") return { pool: "any" as const, label: "Random name", name: randomCharacterName("any", random) };
  return null;
}

